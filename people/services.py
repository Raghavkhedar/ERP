from django.db import transaction
from django.db.models import Q
from django.utils import timezone

from .models import Person


class StaleCard(Exception):
    """Someone saved the card after this form was opened."""


def _department(key, sub):
    """ "Operations / Elec + Mech" from the stored key and sub-department."""
    from hiring.models import Requisition  # hiring imports people

    name = dict(Requisition.Department.choices).get(key, key)
    return " / ".join(x for x in (name, sub) if x)


